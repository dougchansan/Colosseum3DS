#!/usr/bin/env python3
"""Prepare GC6E01 new-game tables from the user's verified original files.

The pack contains original data and must remain private. No save/progress is
created here: trainer ID, personality values, IVs, memo random words and final
stats are generated by the native initializer for the caller's RNG seed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from prepare_boot_media import MAIN_DOL_SHA1, verify_disc
from prepare_model import check_output

SOURCE_COMMIT = "51bfe4314a218dfaf9592fc80723c50498d0ee55"
COMMON_SHA1 = "e816761813900aa0fd4f87d012b3b2a19d2f003e"
COMMON_BYTES = 1369520
BODY_SIZE = 0x1DFD0
PREFIX_SIZE = 0x6040
HEADER_SIZE = 128
FLAG_COUNT = 3593
POKEMON_SIZE = 0x138
PARTY = 0xA0
STARTERS = ((197, 26, 0x4A6F, (0x2C, 0x122, 0x10D, 0x121)),
            (196, 25, 0x3FF4, (0x5D, 0xD8, 0x73, 0x10E)))


def u16(data, offset):
    return struct.unpack_from(">H", data, offset)[0]


def u32(data, offset):
    return struct.unpack_from(">I", data, offset)[0]


def put16(data, offset, value):
    struct.pack_into(">H", data, offset, value)


def put32(data, offset, value):
    struct.pack_into(">I", data, offset, value & 0xFFFFFFFF)


class Dol:
    def __init__(self, data):
        self.data = data

    def read(self, address, length):
        for i in range(18):
            start, size = u32(self.data, 0x48 + 4*i), u32(self.data, 0x90 + 4*i)
            if start <= address and length <= size and address - start <= size - length:
                offset = u32(self.data, 4*i) + address - start
                if offset + length <= len(self.data):
                    return self.data[offset:offset + length]
        raise ValueError(f"DOL address is not mapped: {address:#x}, length {length:#x}")


def message(rel, data_base, group_offset, key):
    """Bounded GSmsgFindMessage table lookup; return the original byte string."""
    base = data_base + group_offset
    count = u16(rel, base + 4)
    if count > 4096 or base + 16 + 8*count > len(rel):
        raise ValueError("Invalid original message table")
    entries = [struct.unpack_from(">II", rel, base + 16 + i*8) for i in range(count)]
    found = [offset for k, offset in entries if k == key]
    if len(found) != 1:
        raise ValueError(f"Expected exactly one message {key:#x}")
    start = found[0]
    end = min((off for _, off in entries if off > start), default=len(rel)-base)
    if start < 16 + 8*count or not start < end <= len(rel)-base:
        raise ValueError("Invalid original message bounds")
    data = rel[base+start:base+end]
    # The only admitted command is BOX's one-byte dynamic value control 0x34.
    p = 0
    while p + 2 <= len(data):
        code = u16(data, p)
        p += 2
        if code == 0:
            return data[:p]
        if code == 0xFFFF:
            if p >= len(data) or data[p] != 0x34:
                raise ValueError("Unsupported new-game message command")
            p += 1
    raise ValueError("Unterminated original message")


def copy_name(body, offset, value, units=11):
    if len(value) > units*2 or len(value) % 2 or not value.endswith(b"\0\0"):
        raise ValueError("Original name does not fit its GSchar destination")
    body[offset:offset+units*2] = value + bytes(units*2-len(value))


def empty_pokemon(body, offset):
    # pokemonInit / PokemonBios: the only nonzero scalar defaults.
    body[offset:offset+POKEMON_SIZE] = bytes(POKEMON_SIZE)
    body[offset+0x10] = 2  # unknown original-trainer sex
    body[offset+0xD0] = 0xFF  # no mail
    put32(body, offset+0xDC, -100)  # no active Shadow gauge


def make_pack(disc):
    disc = verify_disc(disc)
    path = disc / "files/common_rel.rel"
    if path.is_symlink() or path.stat().st_size != COMMON_BYTES:
        raise ValueError("Unexpected common_rel.rel path/size")
    rel = path.read_bytes()
    if hashlib.sha1(rel).hexdigest() != COMMON_SHA1:
        raise ValueError("common_rel.rel differs from pinned GC6E01")
    dol = Dol((disc / "sys/main.dol").read_bytes())
    sections = u32(rel, 0x10)
    if u32(rel, 0x0C) != 11:
        raise ValueError("Unexpected common_rel section count")
    data_base = u32(rel, sections + 4*8)
    if data_base != 0x184C or u32(rel, sections + 4*8+4) != 0x14A714:
        raise ValueError("Unexpected common_rel data section")

    body = bytearray(BODY_SIZE)
    # Fresh zeroed body is the path used by memcard.c before savedataCreate.
    body[:4] = bytes((0x0B, 3, 2, 2))  # gamedataCreate, main.c returns USA=1
    put32(body, 0x1C, 2)
    put32(body, 0x24, 1)
    body[0x28] = 1
    put32(body, 0x70+0xA84, 10000)
    body[0x70+0xA90:0x70+0xA98] = b"\1"*8
    partner = message(rel, data_base, 0x58044, 0xFA2)
    copy_name(body, 0x70+0xAC2, partner)
    for i in range(6):
        empty_pokemon(body, PARTY + i*POKEMON_SIZE)

    # heroItemAddItemDataId uses kind2, mode0 compaction for these eight IDs.
    # All are distinct and below cap; their insertion order is preserved.
    items = ((0x16, 2), (0x0D, 5), (0x0E, 2), (0x0F, 2),
             (0x10, 2), (0x12, 2), (0x11, 2), (0x17, 2))
    for i, (item, amount) in enumerate(items):
        slot = u16(dol.read(0x803681E8 + item*2, 2), 0)
        record = dol.read(0x80363CE8 + slot*0x28, 0x28)
        if record[0] != 2 or u32(record, 0x10) == 0:
            raise ValueError("Initial item no longer belongs to the normal bag")
        put16(body, 0x70+0x780+i*4, item)
        put16(body, 0x70+0x782+i*4, amount)

    box_pattern = message(rel, data_base, 0x647B4, 0x32C9)
    command = b"\xff\xff\x34"
    if box_pattern.count(command) != 1:
        raise ValueError("Expected one BOX number substitution")
    for i in range(3):
        offset = 0xB88 + i*0x24A4
        # msgctrlSetValue(0x34,i+1); fn_800F96E4(cur,9,0x32c9).
        name = box_pattern.replace(command, str(i+1).encode("utf-16-be"))
        copy_name(body, offset, name, 9)
        for j in range(30):
            empty_pokemon(body, offset+0x14+j*POKEMON_SIZE)

    # Mailbox clear and 512 u16 sequence handles = 0x00ff (not memset ff).
    body[0x7D20:0x7D20+0x400] = b"\x00\xff"*512
    # Daycare, e-reader area, memo count, flags and ribbons are zero from the
    # cold cleared payload. memoInit's 500 random words are filled natively.
    rules = dol.read(0x80268940, 3*0x54)
    battle = 0xE3E8
    for destination, source in enumerate((0, 1, 2, 0, 0, 0)):
        off = battle+0xC9DC+destination*0x54
        body[off:off+0x54] = rules[source*0x54:(source+1)*0x54]
    for off in (0xCADE, 0xCB32, 0xCB86):
        put16(body, battle+off, 6)
    body[battle+0xCBD4:battle+0xCBDA] = bytes((1, 1, 1, 0, 1, 0))
    # fn_801EF128: 97 slot records and 97 associated metadata records.
    for i in range(97):
        off = 0x1B014+4+97*12+i*24
        row = data_base+0x1439D8+i*0x38
        body[off+0x0E] = i
        put16(body, off+0x14, 0xFFFF)
        put16(body, off+0x10, u16(rel, row+2) if i else 0)
        put16(body, off+0x16, u16(rel, row+8) if i else 0)

    starters = bytearray()
    for species, level, experience, moves in STARTERS:
        row = data_base+0x121A04+species*0x11C
        record = bytearray(64)
        put16(record, 0, species)
        record[2:4] = bytes((level, rel[row+2]))
        put32(record, 4, experience)
        put16(record, 8, 220)
        record[10:22] = rel[row+0x84:row+0x90]
        for i, move in enumerate(moves):
            put16(record, 22+i*3, move)
            record[24+i*3] = rel[data_base+0x11C7C4+move*0x38+1]
        name = message(rel, data_base, 0x58044, u32(rel, row+0x18))
        copy_name(record, 34, name)
        record[56:58] = rel[row+0x32:row+0x34]
        starters.extend(record)

    natures = bytearray()
    for i in range(25):
        row = data_base+0x121614+i*0x28
        for stat in range(5):
            index = rel[row+5+stat]
            if index >= 8:
                raise ValueError("Invalid original nature rate index")
            rate = rel[data_base+0x13E430+index*2:data_base+0x13E432+index*2]
            if rate not in (bytes((90, 100)), bytes((100, 100)), bytes((110, 100))):
                raise ValueError("Unexpected original nature multiplier")
            natures.extend(rate)

    flags = bytearray(rel[data_base+0x111E04:data_base+0x111E04+FLAG_COUNT*8])
    next_bit = [0, 0, 0, 0]
    for i in range(FLAG_COUNT):
        kind, width = flags[i*8] >> 6, flags[i*8] & 63
        width = min(32, max(1, width))  # GSflagInitBitPos validation
        flags[i*8] = kind*64 + width
        if kind:
            put16(flags, i*8+4, next_bit[kind])
            next_bit[kind] += width
    if any(next_bit[k] > capacity for k, capacity in ((1, 256), (2, 1024), (3, 12288))):
        raise ValueError("Original flag definitions exceed save buffers")

    prefix = bytearray(PREFIX_SIZE)
    # Standard GCI directory entry, with the original game's CARD attributes.
    prefix[:6] = b"GC6E01"
    prefix[6:8] = b"\xff\x02"
    filename = b"pokemon_colosseum\0"
    prefix[8:8+len(filename)] = filename
    put32(prefix, 0x2C, 0x40)
    put16(prefix, 0x30, 0x5555)  # eight C8 icons
    put16(prefix, 0x32, 0xAAAA)  # middle frame speed
    prefix[0x34] = 0x1C
    put16(prefix, 0x36, 0xFFFF)
    put16(prefix, 0x38, 48)
    put16(prefix, 0x3A, 0xFFFF)
    raw = 0x40
    title, comment = b"POK\xe9MON COLOSSEUM\0", b"SAVE FILE\0"
    prefix[raw:raw+len(title)] = title
    prefix[raw+0x20:raw+0x20+len(comment)] = comment
    prefix[raw+0x40:raw+0x3A40] = dol.read(0x802758E8, 0x3A00)
    put32(prefix, raw+0x3A40,
          sum(u32(prefix, raw+off) for off in range(0, 0x3A40, 4)))

    header = bytearray(HEADER_SIZE)
    header[:4] = b"C3GS"
    offsets = []
    payload = bytearray()
    for section in (body, prefix, starters, natures, flags):
        offsets.append(HEADER_SIZE+len(payload))
        payload.extend(section)
    words = (1, HEADER_SIZE+len(payload), offsets[0], BODY_SIZE,
             offsets[1], PREFIX_SIZE, offsets[2], 2, 64,
             offsets[3], 25, 10, offsets[4], FLAG_COUNT, 8)
    struct.pack_into(">15I", header, 4, *words)
    header[64:84] = hashlib.sha1(payload).digest()
    header[84:104] = bytes.fromhex(SOURCE_COMMIT)
    put32(header, 104, 1)
    result = bytes(header+payload)
    metadata = {"source_commit": SOURCE_COMMIT, "main_dol_sha1": MAIN_DOL_SHA1,
                "common_rel_sha1": COMMON_SHA1,
                "bytes": len(result), "sha256": hashlib.sha256(result).hexdigest(),
                "body_bytes": BODY_SIZE, "flag_bits": next_bit,
                "starter_order": [s[0] for s in STARTERS],
                "partner_initial_message": "0xFA2", "save_file_created": False}
    return result, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--disc", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = check_output(args.output)
    pack, metadata = make_pack(args.disc)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("xb") as stream:
        stream.write(pack)
    with output.with_suffix(output.suffix+".json").open("x") as stream:
        json.dump(metadata, stream, indent=2)
        stream.write("\n")
    print(f"Prepared {len(pack)} private bytes: {output}")


if __name__ == "__main__":
    main()
